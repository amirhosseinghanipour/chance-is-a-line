"""Export APA 7th (sn-apa) LaTeX tables, macros, and full audit files."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

CITE_MAP = {
    "schemmer2023": r"\citet{schemmer2023}",
    "vonfelten2025": r"\citet{vonfelten2025}",
    "he2023": r"\citet{he2023}",
    "vasconcelos2023": r"\citet{vasconcelos2023}",
}

LABEL_MAP = {
    "control_no_explanation": "Control",
    "feature_importance": "Feature importance",
    "balanced": "Balanced AI",
    "unbalanced": "Unbalanced AI",
    "under_before_tutorial": "Underestimators, pre-tutorial",
    "under_after_tutorial": "Underestimators, post-tutorial",
    "over_before_tutorial": "Overestimators, pre-tutorial",
    "over_after_tutorial": "Overestimators, post-tutorial",
    "high_performers": "High performers",
    "low_performers_DKE": "Low performers",
    "hard_prediction_only": "Hard, prediction only",
    "hard_highlight_explanation": "Hard, highlight explanation",
    "salient_explanation": "Salient explanation (Study 3)",
}

DENOM_LABEL = {
    "disagreement": "Disagreement (confounded)",
    "all": "All trials (confounded)",
    "ai_wrong": "AI-wrong (invariant)",
}


def _fmt(v: Any, dp: int = 2) -> str:
    return "--" if pd.isna(v) else f"{float(v):.{dp}f}"


def export_brm_artifacts(res_dir: Path, prisma_csv: Path) -> list[Path]:
    """Generate LaTeX macros, APA 7th tables, and full verbatim audit CSV/MD."""
    cond_df = pd.read_csv(res_dir / "conditions_with_J.csv")
    cov_df = pd.read_csv(res_dir / "ci_coverage_validation.csv")
    claims = json.loads((res_dir / "claims.json").read_text())
    analytic = json.loads((res_dir / "claims_analytic.json").read_text())
    val = json.loads((res_dir / "validation_summary.json").read_text())

    # 1. Macros
    macro_lines = [
        "% Auto-generated by chance_is_a_line.export -- DO NOT HAND-EDIT",
        f"\\newcommand{{\\NumPapers}}{{{claims['n_papers']}}}",
        f"\\newcommand{{\\NumConditionGroups}}{{{claims['n_condition_groups']}}}",
        f"\\newcommand{{\\NumConditions}}{{{claims['n_conditions']}}}",
        f"\\newcommand{{\\NumExpArms}}{{{claims['n_experimental_conditions']}}}",
        f"\\newcommand{{\\NumSubgroups}}{{{claims['n_participant_subgroups']}}}",
        f"\\newcommand{{\\NumJIdentified}}{{{claims['n_J_identified']}}}",
        f"\\newcommand{{\\NumJUnidentified}}{{{claims['n_J_unidentified']}}}",
        f"\\newcommand{{\\NumJNegative}}{{{claims['n_J_negative']}}}",
        f"\\newcommand{{\\NumJNearZero}}{{{claims['n_J_near_zero']}}}",
        f"\\newcommand{{\\NumJPositive}}{{{claims['n_J_positive']}}}",
        f"\\newcommand{{\\NumReportedAH}}{{{claims['reported_a_H']}}}",
        f"\\newcommand{{\\NumReportedOver}}{{{claims['reported_over_reliance']}}}",
        f"\\newcommand{{\\NumReportedSD}}{{{claims['reported_sd']}}}",
        f"\\newcommand{{\\NumConfoundedDenom}}{{{claims['n_conditions_confounded_denominator']}}}",
        f"\\newcommand{{\\NumInvariantDenom}}{{{claims['n_conditions_invariant_denominator']}}}",
        f"\\newcommand{{\\MaxConditionN}}{{{claims['N_per_condition_max']}}}",
        f"\\newcommand{{\\MeanConditionN}}{{{claims['N_per_condition_mean']:.1f}}}",
        f"\\newcommand{{\\MedianConditionN}}{{{claims['N_per_condition_median']:.0f}}}",
        f"\\newcommand{{\\MedianHalfWidth}}{{{claims['median_half_width']:.3f}}}",
        f"\\newcommand{{\\MedianHalfWidthTotalDeff}}{{{claims['median_half_width_total_deff']:.3f}}}",
        f"\\newcommand{{\\CrossingNTen}}{{{claims['crossing_N']['10']:.0f}}}",
        f"\\newcommand{{\\CrossingNTwenty}}{{{claims['crossing_N']['20']:.0f}}}",
        f"\\newcommand{{\\CrossingNForty}}{{{claims['crossing_N']['40']:.0f}}}",
        f"\\newcommand{{\\MaxNullLineDev}}{{{analytic['claim1_max_abs_dev_from_null_line']:.4f}}}",
        f"\\newcommand{{\\ReconMaxErrJ}}{{{val['recon_max_abs_err_J']:.4f}}}",
        f"\\newcommand{{\\IccBiasMFour}}{{{val['icc_bias_m4_rho10']:.3f}}}",
        f"\\newcommand{{\\IccBiasMEight}}{{{val['icc_bias_m8_rho10']:.3f}}}",
        f"\\newcommand{{\\IccBiasMTwenty}}{{{val['icc_bias_m20_rho10']:.3f}}}",
        f"\\newcommand{{\\CovNaiveRhoTen}}{{{val['cov_naive_rho10']*100:.1f}}}",
        f"\\newcommand{{\\CovCellRhoTen}}{{{val['cov_cell_true_rho10']*100:.1f}}}",
        f"\\newcommand{{\\CovPluginRhoTen}}{{{val['cov_cell_plugin_rho10']*100:.1f}}}",
        f"\\newcommand{{\\CovNaiveRhoTwenty}}{{{val['cov_naive_rho20']*100:.1f}}}",
        f"\\newcommand{{\\CovCellRhoTwenty}}{{{val['cov_cell_true_rho20']*100:.1f}}}",
        f"\\newcommand{{\\CovPluginRhoTwenty}}{{{val['cov_cell_plugin_rho20']*100:.1f}}}",
    ]
    if prisma_csv.exists():
        for _, row in pd.read_csv(prisma_csv).iterrows():
            key, cnt = str(row["macro_name"]).strip(), str(row["count"]).strip()
            if key:
                macro_lines.append(f"\\newcommand{{\\{key}}}{{{cnt}}}")
    p_macros = res_dir / "manuscript_macros.tex"
    p_macros.write_text("\n".join(macro_lines) + "\n")

    # 2. Table 1 (Recomputed J)
    ident = cond_df[cond_df.J.notna()].copy()
    t1 = [
        r"\begin{table}[t]",
        r"\caption{Youden's $J$ recomputed from reported RAIR and RSR across the ten recoverable conditions. Values match the decimal precision of the original sources; $J$ is computed prior to rounding. Randomized experimental arms and post-hoc subgroups are separated without pooling, and subgroups from \citet{he2023} contain overlapping participants.}\label{tab:main}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}llrrr}",
        r"\toprule",
        r"Study & Condition & RAIR & RSR & $J$ \\",
        r"\midrule",
        r"\multicolumn{5}{l}{\emph{Randomized experimental conditions}} \\",
    ]
    for rt, hdr in [
        ("experimental_condition", None),
        ("participant_subgroup", r"\multicolumn{5}{l}{\emph{Post-hoc participant subgroups}} \\"),
    ]:
        if hdr:
            t1.extend([r"\addlinespace[4pt]", hdr])
        for _, r in ident[ident.row_type == rt].iterrows():
            dp = 4 if r.paper_id == "schemmer2023" else 2
            t1.append(
                f"{CITE_MAP.get(r.paper_id, r.paper_id)} & {LABEL_MAP.get(r.condition_label, r.condition_label)} "
                f"& {r.rair:.{dp}f} & {r.rsr:.{dp}f} & ${r.J:+.3f}$ \\\\"
            )
    t1.extend([r"\botrule", r"\end{tabular*}", r"\end{table}"])
    p_t1 = res_dir / "table1_recomputed_J.tex"
    p_t1.write_text("\n".join(t1) + "\n")

    # 3. CI coverage table
    tc = [
        r"\begin{table}[t]",
        r"\caption{Monte Carlo empirical 95\% confidence interval coverage for Youden's $J$ across true intraclass correlation $\rho$ ($N=120$ participants, $m=60$ trials, $a_H=0.60$, $a_A=0.70$, 500 replications per cell).}\label{tab:coverage}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}rrrrr}",
        r"\toprule",
        r"True $\rho$ & Naive ($\rho=0$) & Cell-DEFF (true $\rho$) & Cell-DEFF (plug-in $\hat{\rho}$) & Total-DEFF (conservative) \\",
        r"\midrule",
    ]
    for _, r in cov_df.iterrows():
        tc.append(
            f"{r.rho_true:.2f} & {r.cov_naive*100:.1f}\\% & {r.cov_cell_true*100:.1f}\\% & "
            f"{r.cov_cell_plugin*100:.1f}\\% & {r.cov_total_true*100:.1f}\\% \\\\"
        )
    tc.extend([r"\botrule", r"\end{tabular*}", r"\end{table}"])
    p_tc = res_dir / "tableC1_ci_coverage.tex"
    p_tc.write_text("\n".join(tc) + "\n")

    # 4. Extraction audit summary table
    tb = [
        r"\begin{table}[t]",
        r"\caption{Summary of the extraction audit across all 13 conditions in four published studies. Full verbatim quotations and explicit \texttt{DERIVED:} arithmetic notes are archived in the open supplementary audit files.}\label{tab:audit}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}p{2.3cm}p{2.4cm}crrcccl}",
        r"\toprule",
        r"Study & Condition & $k$ & $N$ & $m$ & $a_H$ & $a_A$ & $J$ status & Over-reliance denom. \\",
        r"\midrule",
    ]
    for _, r in cond_df.iterrows():
        a_h = f"{r.a_H_initial:.4f}" if pd.notna(r.a_H_initial) else "NR"
        a_a = f"{r.a_A_actual:.3f}" if r.paper_id == "he2023" else f"{r.a_A_actual:.2f}"
        jst = "Exact" if r.J_method == "exact" else r"Undef.\ (design)"
        tb.append(
            f"{CITE_MAP.get(r.paper_id, r.paper_id)} & {LABEL_MAP.get(r.condition_label, r.condition_label)} "
            f"& {int(r.k_options)} & {int(r.n_participants)} & {int(r.n_trials_per_participant)} "
            f"& {a_h} & {a_a} & {jst} & {DENOM_LABEL.get(r.over_reliance_denominator, r.over_reliance_denominator)} \\\\"
        )
    tb.extend(
        [
            r"\botrule",
            r"\end{tabular*}",
            r"\footnotetext{Note: NR = not reported; $m$ = trials per participant (for \citealt{vasconcelos2023}, 3 AI-incorrect trials out of 15 hard-condition test questions). Ten of 13 conditions use the disagreement denominator (confounded with $a_A$); 3 of 13 (\citealt{vasconcelos2023}) use the AI-wrong denominator (invariant to $a_A$).}",
            r"\end{table}",
        ]
    )
    p_tb = res_dir / "tableB1_extraction_audit.tex"
    p_tb.write_text("\n".join(tb) + "\n")

    # 5. Full verbatim audit CSV & Markdown
    cols = [
        "paper_id", "study_id", "citation", "row_type", "condition_label",
        "k_options", "n_participants", "n_trials_per_participant",
        "a_H_initial", "a_A_stated", "a_A_actual", "rair", "rsr", "J",
        "J_method", "over_reliance", "over_reliance_denominator",
        "evidence_rair", "evidence_rsr", "evidence_a_H", "evidence_a_A",
        "evidence_n", "evidence_trials", "evidence_over",
        "evidence_over_denominator", "interpretation_note",
    ]
    audit_df = cond_df[[c for c in cols if c in cond_df.columns]].copy()
    p_acsv = res_dir / "extraction_audit_full.csv"
    audit_df.to_csv(p_acsv, index=False)

    md_lines = ["# Full Extraction Audit — Chance Is a Line\n"]
    for idx, r in audit_df.iterrows():
        md_lines.append(f"## {idx + 1}. {r['citation']} — `{r['condition_label']}` (`{r['row_type']}`)")
        md_lines.append(
            f"- **Design:** k={int(r['k_options'])}, N={int(r['n_participants'])}, "
            f"m={int(r['n_trials_per_participant'])}, a_H={_fmt(r['a_H_initial'], 4)}, "
            f"a_A_actual={_fmt(r['a_A_actual'], 3)}"
        )
        md_lines.append(
            f"- **Metrics:** RAIR={_fmt(r['rair'], 4)}, RSR={_fmt(r['rsr'], 4)}, "
            f"J={_fmt(r['J'], 4)} ({r['J_method']}), over-reliance={_fmt(r['over_reliance'], 4)} "
            f"(denom: `{r['over_reliance_denominator']}`)"
        )
        for ev in (
            "evidence_rair", "evidence_rsr", "evidence_a_H", "evidence_a_A",
            "evidence_n", "evidence_trials", "evidence_over", "evidence_over_denominator",
        ):
            val = r.get(ev)
            if pd.notna(val) and str(val).strip():
                md_lines.append(f"  - `{ev}`: {val}")
        md_lines.append(f"- **Note:** {r['interpretation_note']}\n")
    p_amd = res_dir / "extraction_audit_full.md"
    p_amd.write_text("\n".join(md_lines))

    return [p_macros, p_t1, p_tc, p_tb, p_acsv, p_amd]
